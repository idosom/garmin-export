/**
 * A curated subset of the Garmin FIT profile.
 *
 * The FIT profile is huge and grows with every SDK release, so this table is
 * deliberately *not* treated as exhaustive: the decoder falls back to
 * `mesg_<num>` / `field_<num>` for anything missing, keeps the raw values, and
 * reports them as unknown fields so they still show up in the Data Explorer.
 * Adding a row here upgrades a raw field to a named one — nothing else changes.
 */

export interface FitFieldDef {
  name: string;
  /** value = raw / scale - offset */
  scale?: number;
  offset?: number;
  units?: string;
  /** Name of an enum in `FIT_ENUMS`. */
  enum?: string;
  /** sint32 semicircles → degrees. */
  semicircles?: boolean;
  /** uint32 FIT seconds → epoch ms. */
  dateTime?: boolean;
}

export interface FitMesgDef {
  name: string;
  fields: Record<number, FitFieldDef>;
}

const f = (
  name: string,
  extra: Omit<FitFieldDef, 'name'> = {},
): FitFieldDef => ({ name, ...extra });

const ts = f('timestamp', { dateTime: true });

