export function mesgName(num: number): string {
  return FIT_MESSAGES[num]?.name ?? `mesg_${num}`;
}

export function fieldDef(mesgNum: number, fieldNum: number): FitFieldDef | undefined {
  return FIT_MESSAGES[mesgNum]?.fields[fieldNum];
}

export function enumValue(enumName: string | undefined, raw: number): string | number {
  if (!enumName) return raw;
  const table = FIT_ENUMS[enumName];
  if (!table) return raw;
  return table[raw] ?? raw;
}
